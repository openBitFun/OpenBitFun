import { readFileSync, writeFileSync } from 'node:fs';
import { compileCatalog } from '../src/shared/generative-ui/library.mjs';
const path = new URL('../src/shared/generative-ui/', import.meta.url);
const catalog = compileCatalog(JSON.parse(readFileSync(new URL('library.json', path), 'utf8')));
const output = JSON.stringify(catalog, null, 2) + '\n';
const target = new URL('catalog.json', path);

// The NSH renderer reads OpenUI Lang itself, so it needs every component's
// positional argument order: the order the prompt shows the model (slots, then
// required props, then the action, then optional props). Profiles share
// component names and argument order: the OpenBitFun library's order is the
// one both profile prompts show (the `openui` profile's upstream prompt lists
// `ListItem(title, …, children?)` too), so it is read first and the other
// libraries only add what it lacks.
function argumentNames(component) {
  const properties = component.props?.properties ?? {};
  const required = new Set(component.props?.required ?? []);
  return [
    ...Object.keys(component.slots ?? {}),
    ...Object.keys(properties).filter(key => required.has(key)),
    ...(component.action ? ['action'] : []),
    ...Object.keys(properties).filter(key => !required.has(key)),
  ];
}
const signatures = {};
const libraries = Object.entries(catalog.libraries).sort(([left], [right]) =>
  Number(right === 'openbitfun.composable.v1') - Number(left === 'openbitfun.composable.v1'));
for (const [, library] of libraries) {
  for (const [name, component] of Object.entries(library.components)) {
    signatures[name] ??= argumentNames(component);
  }
}
const nshTarget = new URL('../src/nsh-ui/src/genui/genuiSignatures.ts', import.meta.url);
const nshOutput = [
  '// Generated by scripts/generate-genui-contract.mjs from src/shared/generative-ui/library.json.',
  '// Positional argument names of every GenUI component, in the order the model is prompted with.',
  '// Do not edit by hand.',
  '',
  'export const COMPONENT_SIGNATURES: Readonly<Record<string, readonly string[]>> = {',
  ...Object.keys(signatures).sort().map(name => `  ${name}: [${signatures[name].map(arg => JSON.stringify(arg)).join(', ')}],`),
  '};',
  '',
  '/** OpenUI action steps (`@Name(...)`): they run when pressed instead of when evaluated. */',
  'export const ACTION_STEPS: ReadonlySet<string> = new Set(["ToAssistant", "OpenUrl", "Set", "Reset", "CopyToClipboard"]);',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('GenUI catalog is stale; run node scripts/generate-genui-contract.mjs');
  if (readFileSync(nshTarget, 'utf8') !== nshOutput) throw new Error('NSH GenUI signatures are stale; run node scripts/generate-genui-contract.mjs');
} else {
  writeFileSync(target, output);
  writeFileSync(nshTarget, nshOutput);
}
