use std::collections::HashMap;
use std::fs;
use std::io::Write;
use std::path::Path;

fn main() {
    // Cargo does not propagate a dependency's link-arg to the final executable.
    // Keep the shared provider optional on macOS older than ScreenCaptureKit.
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        println!("cargo:rustc-link-arg=-Wl,-weak_framework,ScreenCaptureKit");
    }
    if let Err(e) = embed_cli_prompts() {
        eprintln!("Warning: Failed to embed CLI prompts: {}", e);
    }
    embed_web_ui_bundle();
}

/// Compiles the NSH web UI bundle into the executable when
/// `OPENBITFUN_CLI_WEB_UI_DIR` names one (`ui-bundle.json` and its files; the
/// CLI build and install scripts build it from the same tree first). The CLI
/// hands browsers exactly this bundle (`ui_bundle_manifest`, `src/ui_bundle.rs`);
/// embedding keeps it the same commit as the binary through `cargo install`,
/// self-update and copies. Without the variable the CLI answers
/// `ui_bundle_unavailable`. `.gz` siblings are never served and are skipped;
/// the runtime checks every embedded file against the manifest.
fn embed_web_ui_bundle() {
    const VARIABLE: &str = "OPENBITFUN_CLI_WEB_UI_DIR";
    println!("cargo:rerun-if-env-changed={VARIABLE}");
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let dest = Path::new(&out_dir).join("embedded_ui_bundle.rs");
    let mut code =
        String::from("// Auto-generated by build.rs from OPENBITFUN_CLI_WEB_UI_DIR; do not edit\n");
    let dir = std::env::var_os(VARIABLE).filter(|value| !value.is_empty());
    match dir {
        None => {
            code.push_str("pub(crate) const EMBEDDED_UI_MANIFEST: Option<&[u8]> = None;\n");
            code.push_str("pub(crate) static EMBEDDED_UI_FILES: &[(&str, &[u8])] = &[];\n");
        }
        Some(dir) => {
            let root = Path::new(&dir)
                .canonicalize()
                .unwrap_or_else(|e| panic!("{VARIABLE}={dir:?} is not readable: {e}"));
            let manifest = root.join("ui-bundle.json");
            assert!(
                manifest.is_file(),
                "{VARIABLE}={} has no ui-bundle.json; run scripts/write-ui-bundle-manifest.mjs on it",
                root.display()
            );
            println!("cargo:rerun-if-changed={}", manifest.display());
            println!("cargo:rerun-if-changed={}", root.display());
            let mut files = Vec::new();
            collect_bundle_files(&root, &root, &mut files);
            files.sort();
            code.push_str(&format!(
                "pub(crate) const EMBEDDED_UI_MANIFEST: Option<&[u8]> = Some(include_bytes!({:?}));\n",
                manifest.display().to_string()
            ));
            code.push_str("pub(crate) static EMBEDDED_UI_FILES: &[(&str, &[u8])] = &[\n");
            for (relative, absolute) in &files {
                code.push_str(&format!(
                    "    ({relative:?}, include_bytes!({:?})),\n",
                    absolute.display().to_string()
                ));
            }
            code.push_str("];\n");
            println!("Embedded the web UI bundle: {} files", files.len());
        }
    }
    fs::write(&dest, code).expect("write embedded_ui_bundle.rs");
}

fn collect_bundle_files(root: &Path, dir: &Path, files: &mut Vec<(String, std::path::PathBuf)>) {
    let entries = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read the web UI bundle at {}: {e}", dir.display()));
    for entry in entries {
        let path = entry.expect("web UI bundle entry").path();
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or("");
        if name.starts_with('.') || name.ends_with(".gz") {
            continue;
        }
        if path.is_dir() {
            collect_bundle_files(root, &path, files);
        } else if path.is_file() && name != "ui-bundle.json" {
            let relative = path
                .strip_prefix(root)
                .expect("bundle file under its root")
                .to_string_lossy()
                .replace('\\', "/");
            files.push((relative, path));
        }
    }
}

fn embed_cli_prompts() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR")?;
    let prompts_dir = Path::new(&manifest_dir).join("prompts");

    println!("cargo:rerun-if-changed=prompts");

    let mut prompts = HashMap::new();

    if prompts_dir.exists() {
        read_prompt_files(&prompts_dir, &prompts_dir, &mut prompts)?;
    }

    generate_prompts_code(&prompts)?;

    println!("Embedded {} CLI prompt(s)", prompts.len());
    Ok(())
}

fn read_prompt_files(
    current_dir: &Path,
    base_dir: &Path,
    prompts: &mut HashMap<String, String>,
) -> Result<(), Box<dyn std::error::Error>> {
    for entry in fs::read_dir(current_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.is_dir() {
            read_prompt_files(&path, base_dir, prompts)?;
        } else if matches!(
            path.extension().and_then(|e| e.to_str()),
            Some("md" | "txt")
        ) {
            let content = fs::read_to_string(&path)?;
            let relative = path
                .strip_prefix(base_dir)?
                .to_string_lossy()
                .replace('\\', "/");
            // Key: filename without extension, e.g. "init" from "init.md"
            let key = relative
                .trim_end_matches(".md")
                .trim_end_matches(".txt")
                .to_string();
            prompts.insert(key, content);
        }
    }
    Ok(())
}

fn generate_prompts_code(
    prompts: &HashMap<String, String>,
) -> Result<(), Box<dyn std::error::Error>> {
    let out_dir = std::env::var("OUT_DIR")?;
    let dest = Path::new(&out_dir).join("embedded_cli_prompts.rs");
    let mut f = fs::File::create(&dest)?;

    writeln!(f, "// Auto-generated by build.rs — do not edit")?;
    writeln!(f)?;
    writeln!(f, "use std::collections::HashMap;")?;
    writeln!(f, "use once_cell::sync::Lazy;")?;
    writeln!(f)?;
    writeln!(
        f,
        "static CLI_PROMPTS: Lazy<HashMap<&'static str, &'static str>> = Lazy::new(|| {{"
    )?;
    writeln!(f, "    let mut m = HashMap::new();")?;

    // Sort keys so the generated file is byte-identical across builds
    // (HashMap iteration order is randomized; determinism keeps build caches
    // effective and output reproducible).
    let mut sorted: Vec<(&String, &String)> = prompts.iter().collect();
    sorted.sort_by(|a, b| a.0.cmp(b.0));
    for (key, content) in sorted {
        writeln!(
            f,
            "    m.insert(r###\"{}\"###, r###\"{}\"###);",
            key, content
        )?;
    }

    writeln!(f, "    m")?;
    writeln!(f, "}});")?;
    writeln!(f)?;

    writeln!(f, "/// Get an embedded CLI prompt by name")?;
    writeln!(
        f,
        "pub(crate) fn get_cli_prompt(name: &str) -> Option<&'static str> {{"
    )?;
    writeln!(f, "    CLI_PROMPTS.get(name).copied()")?;
    writeln!(f, "}}")?;

    Ok(())
}
