//! Compiled rows of the Product Operation Registry.
//!
//! One row per product operation reachable over a host boundary. Rows are
//! sorted by id and kept one per line so that a new command has exactly one
//! insertion point and a review diff shows exactly one row.
//! `#[rustfmt::skip]` keeps that layout; `operations_are_sorted_and_unique`
//! in `mod.rs` verifies lookup coverage; a const assertion also rejects invalid builds.
//!
//! Columns: id, remote workspace stance, peer stance, CLI peer host support.
//! Desktop peer host support is derived (see `OperationDefinition::host_support`).
//!
//! Adding a backend command: register it in `backend_commands!` in
//! `src/apps/desktop/src/lib.rs`, then add one `op(...)` row here with a real
//! stance for every column. `Unaudited` is a frozen backlog and may not be used
//! for new rows (see `baseline.rs`). Removing one: replace its row with
//! `retired(...)` so older clients get an explicit answer.

use super::{
    HostSupport, OperationDefinition, OperationSurface, PeerStance, RemoteWorkspaceStance,
};
use PeerStance::{ControllerLocal, FleetEntry, HostControlPlane, OperatorOnly, Proxied};
use RemoteWorkspaceStance::{Agnostic, LocalOnly, Routed, Unaudited, Unsupported};

const fn op(
    id: &'static str,
    remote_workspace: RemoteWorkspaceStance,
    peer: PeerStance,
    cli_peer: HostSupport,
) -> OperationDefinition {
    OperationDefinition {
        id,
        surface: OperationSurface::TauriCommand,
        remote_workspace,
        peer,
        cli_peer,
        cloud_peer: CLOUD_NOT_SERVED,
    }
}

/// A HostInvoke name that is not a registered Tauri command: CLI peer host
/// aliases kept for older controllers, and the detached-dispatch target verbs.
const fn host_invoke_only(
    id: &'static str,
    remote_workspace: RemoteWorkspaceStance,
    peer: PeerStance,
    cli_peer: HostSupport,
) -> OperationDefinition {
    OperationDefinition {
        id,
        surface: OperationSurface::HostInvokeOnly,
        remote_workspace,
        peer,
        cli_peer,
        cloud_peer: CLOUD_NOT_SERVED,
    }
}

/// A command only the account's cloud node serves (`superagent_*`).
/// Frontends send it with `fleet_call {target: "cloud-…"}` (`ByTarget`); it
/// never depends on a workspace filesystem (Agnostic), and desktop and CLI
/// hosts answer it unsupported.
const fn cloud_node(id: &'static str) -> OperationDefinition {
    OperationDefinition {
        id,
        surface: OperationSurface::CloudNode,
        remote_workspace: RemoteWorkspaceStance::Agnostic,
        peer: PeerStance::Proxied,
        cli_peer: CLI_CLOUD_NODE_ONLY,
        cloud_peer: HostSupport::Handled,
    }
}

const RETIRED_GENUI_PROVIDER: &str = "the legacy GenUI provider has been retired";

/// A tombstone for a command that no longer exists: it stays in the registry
/// so every host and older client gets the stable retirement message
/// ("command '<id>' is unsupported because <reason>") instead of an
/// unknown-command error. It is not a registered command.
const fn retired(id: &'static str, reason: &'static str) -> OperationDefinition {
    OperationDefinition {
        id,
        surface: OperationSurface::HostInvokeOnly,
        remote_workspace: RemoteWorkspaceStance::LocalOnly,
        peer: PeerStance::Retired { reason },
        cli_peer: HostSupport::Unsupported { reason },
        cloud_peer: HostSupport::Unsupported { reason },
    }
}

